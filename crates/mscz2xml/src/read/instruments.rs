/// Reconnaissance d'un instrument 3.x sans identifiant MusicXML.
///
/// Portage de `Instrument::updateInstrumentId` (`recognizeMusicXmlId`) et de
/// `Instrument::recognizeMidiProgram` : les partitions antérieures à 3.6 ne
/// stockent ni identifiant MusicXML ni programme MIDI par défaut. Les noms
/// (piste, long, court) désignent un instrument du catalogue ; à défaut, le
/// programme déjà lu, puis `keyboard.piano`.
///
/// Renvoie l'identifiant MusicXML et le programme reconnu. Le programme lu
/// dans le fichier prime : `update_instrument` ne le remplace que s'il manque.
pub(crate) fn recognize(
    music_xml_id: &str,
    names: [&str; 3],
    program: Option<i16>,
) -> (String, Option<i16>) {
    let by_name = template_for_names(&names);
    let music_xml_id = if !music_xml_id.is_empty() {
        // L'identifiant écrit prime ; `updateInstrumentId` ne le remplace pas.
        music_xml_id
    } else if let Some(template) = by_name {
        template.music_xml_id
    } else if let Some(program) = program {
        template_for_program(program).map_or(DEFAULT_MUSIC_XML_ID, |template| template.music_xml_id)
    } else if names
        .iter()
        .any(|name| name.to_lowercase().contains("piano"))
    {
        "keyboard.piano"
    } else {
        DEFAULT_MUSIC_XML_ID
    };

    let program = program.or_else(|| {
        by_name
            .filter(|template| template.music_xml_id == music_xml_id)
            .and_then(|template| template.program)
            .or_else(|| {
                template_for_music_xml_id(music_xml_id).and_then(|template| template.program)
            })
    });

    (music_xml_id.to_owned(), program)
}

/// Identifiant MusicXML de repli (`recognizeMusicXmlId`).
const DEFAULT_MUSIC_XML_ID: &str = "keyboard.piano";

/// Cherche un instrument par ses noms, comme `searchTemplateForInstrNameList`.
///
/// Poids de MuseScore : 4 pour le nom de piste, 2 pour le nom long, 1 pour le
/// nom court. À force égale, le premier du catalogue l'emporte. Si aucun nom ne
/// correspond, « piano » dans un nom renvoie le piano générique.
fn template_for_names(names: &[&str; 3]) -> Option<&'static Template> {
    let mut best = None;
    let mut best_strength = 0;
    for name in names {
        let name = name.trim();
        if name.is_empty() {
            continue;
        }
        for template in TEMPLATES {
            let strength = 4 * u8::from(template.track_name.eq_ignore_ascii_case(name))
                + 2 * u8::from(template.long_name.eq_ignore_ascii_case(name))
                + u8::from(template.short_name.eq_ignore_ascii_case(name));
            if strength > best_strength {
                best = Some(template);
                best_strength = strength;
            }
        }
    }
    if best.is_none()
        && names
            .iter()
            .any(|name| name.to_lowercase().contains("piano"))
    {
        return template_for_id("piano");
    }
    best.filter(|template| !template.music_xml_id.is_empty())
}

/// Premier instrument du catalogue dont le programme MIDI vaut `program`.
fn template_for_program(program: i16) -> Option<&'static Template> {
    TEMPLATES
        .iter()
        .find(|template| template.program == Some(program) && !template.music_xml_id.is_empty())
}

/// Instrument le plus générique portant un identifiant MusicXML donné.
///
/// `Instrument::recognizeId` préfère les identifiants courts (« piano » plutôt
/// que « grand-piano ») quand plusieurs instruments partagent le même
/// identifiant MusicXML.
fn template_for_music_xml_id(music_xml_id: &str) -> Option<&'static Template> {
    TEMPLATES
        .iter()
        .filter(|template| template.music_xml_id == music_xml_id)
        .min_by_key(|template| template.id.len())
}

/// Premier instrument du catalogue portant un identifiant MuseScore donné.
fn template_for_id(id: &str) -> Option<&'static Template> {
    TEMPLATES.iter().find(|template| template.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn recognized(
        music_xml_id: &str,
        names: [&str; 3],
        program: Option<i16>,
    ) -> (String, Option<i16>) {
        recognize(music_xml_id, names, program)
    }

    #[test]
    fn reconnait_par_le_nom_de_piste() {
        assert_eq!(
            recognized("", ["Flute", "", ""], Some(73)),
            ("wind.flutes.flute".to_owned(), Some(73))
        );
        assert_eq!(
            recognized("", ["Piano", "", ""], Some(0)),
            ("keyboard.piano".to_owned(), Some(0))
        );
        assert_eq!(
            recognized("", ["Violin", "", ""], Some(40)),
            ("strings.violin".to_owned(), Some(40))
        );
    }

    #[test]
    fn reconnait_par_le_nom_long_et_le_nom_court() {
        // La comparaison est exacte, comme `searchTemplateForInstrNameList`.
        assert_eq!(
            recognized("", ["", "Bass Flute", ""], None).0,
            "wind.flutes.flute.bass"
        );
        assert_eq!(recognized("", ["", "", "Tbn."], None).0, "brass.trombone");
    }

    #[test]
    fn reconnait_le_programme_manquant() {
        // `<Channel/>` vide : MuseScore retrouve le programme de la voix.
        assert_eq!(
            recognized("", ["Voice", "", ""], None),
            ("voice.vocals".to_owned(), Some(52))
        );
        assert_eq!(
            recognized("", ["Flute", "", ""], None),
            ("wind.flutes.flute".to_owned(), Some(73))
        );
    }

    #[test]
    fn garde_l_identifiant_ecrit() {
        assert_eq!(
            recognized("wind.reed.clarinet.a", ["A Clarinet", "", ""], Some(71)),
            ("wind.reed.clarinet.a".to_owned(), Some(71))
        );
    }

    #[test]
    fn retombe_sur_le_piano() {
        assert_eq!(
            recognized("", ["Instrument inconnu", "", ""], None),
            ("keyboard.piano".to_owned(), Some(0))
        );
    }
}
